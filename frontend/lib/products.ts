/**
 * The seven C3 Agency products, transcribed from the commercial proposals
 * (КП, декабрь 2025 — январь 2026). This file is the single source of truth for
 * prices, packages and CTA wording: the site must never contradict a PDF that
 * is already in a client's inbox.
 *
 * Two buying modes, one page template:
 *   - "fixed" — price is on the page, the visitor decides alone and sends a
 *     keyword. No meeting in the funnel.
 *   - "quote" — no price exists until a brief happens. The page sells the
 *     meeting, not the product.
 *
 * Every optional field is a section that simply does not render when absent,
 * so a product with no case studies has no empty case-study block.
 */

export type BuyingModel = "fixed" | "quote";

export type ProductPackage = {
  name: string;
  price: string;
  /** Sub-line under the price — "за 10 роликов", "2 часа под ключ". */
  note?: string;
  includes: string[];
  /** Renders the package as the recommended one. At most one per product. */
  featured?: boolean;
};

export type ProductStep = { title: string; text: string };
export type ProductCase = { title: string; task: string; did: string; result: string };
export type ProductPoint = { title: string; text: string };
export type ProductIncludes = { group: string; items: string[] };

export type Product = {
  slug: string;
  /** Display order across nav, home grid and sitemap. */
  num: string;
  name: string;
  /** One line under the name on the card and in the hero. */
  tagline: string;
  /** Who this is for, in two words, printed on the card. */
  audience: string;
  model: BuyingModel;
  /** Card price line. Absent for quote-model products. */
  priceFrom?: string;
  priceNote?: string;
  /** The keyword from the КП. Pre-fills the chat — this is the whole CTA. */
  ctaWord: string;
  ctaLabel: string;
  /** Hero paragraph. */
  lead: string;
  /** «Если у вас было так» */
  pains?: string[];
  /** «Наше решение» */
  solution?: string;
  /** «Для кого подходит» */
  fitFor?: string[];
  /** «Что мы создаём» */
  deliverables?: string[];
  packages?: ProductPackage[];
  /** «Что входит в пакет», grouped. */
  includes?: ProductIncludes[];
  /** «Как это работает» */
  steps?: ProductStep[];
  /** «Сроки» */
  timeline?: string[];
  /** «Условия» — payment, revisions, anything that prevents an argument later. */
  terms?: string[];
  /** «Почему C3AG» */
  why?: ProductPoint[];
  cases?: ProductCase[];
  geo?: string;
  /**
   * Archive folders holding this product's work, matched as path prefixes
   * against `sourcePath` in data/videos.json. The site's three directions can't
   * tell a podcast from a documentary; the Yandex folders can, and they already
   * map onto the products almost one to one.
   *
   * Empty (or thinner than MIN_WORKS in ProductPage) → the page shows a
   * one-line "examples on request" instead of a grid of placeholders.
   */
  clipFolders?: string[];
  seoTitle: string;
  seoDescription: string;
};

